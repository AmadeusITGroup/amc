VECTOR_TYPES = [
    ("RelocType", "Complex trivially relocatable type"),
    ("Int", "uint32_t"),
    ("NonRelocType", "Complex non trivially relocatable type"),
]
VECTOR_OPS = [
    ("AssignRandom", "Assign a count or a range"),
    ("SwapRandom", "Construct and swap"),
    ("EraseRandom", "Insert at end, erase at front"),
    ("InsertNElemsRandom", "Insert N copies"),
    ("InsertFromPointerRandom", "Insert a range of pointers"),
    ("InsertFromForwardItRandom", "Insert a std::set range"),
    ("Growing", "Grow to 1M by emplace_back"),
]
VECTOR_SERIES = [(STD_ORDERED, "std::vector"), (AMC, "amc::vector")]

SMALL_SIZE = 16  # kSmallSize of vectors_benchmark.cpp
SMALL_VECTOR_SERIES = [(STD_ORDERED, "std::vector"), (AMC_VECTOR, "amc::vector"),
                       (AMC, f"amc::SmallVector<T, {SMALL_SIZE}>")]
SMALL_VECTOR_PREFIX = {STD_ORDERED: "REF", AMC_VECTOR: "AMC", AMC: "AMCSmall"}


def small_vector_rows(bench, type_suffix):
    """Rows of the SmallVector chart: one per percentage of small vectors."""
    rows = []
    percents = sorted({int(k.split("/")[1]) for k in bench if k.startswith(f"SmallSizes<AMCSmall{type_suffix}>/")})
    for percent in percents:
        row = {s: bench.get(f"SmallSizes<{p}{type_suffix}>/{percent}") for s, p in SMALL_VECTOR_PREFIX.items()}
        if None not in row.values():
            label = {0: "All large", 100: "All small"}.get(percent, f"{percent} % small")
            rows.append((label, row))
    return rows

SET_SERIES = [(STD_ORDERED, "std::set"), (STD_HASHED, "std::unordered_set"), (AMC, "amc::FlatSet")]
SET_PREFIX = {STD_ORDERED: "REF", STD_HASHED: "REFUno", AMC: "AMC"}


def set_runs(bench, with_lookups):
    """[(family, run name suffix, label)] of the operations of a set panel present in 'bench'."""
    ops = [("InsertRandom", "", "Insert 200 random values")]
    families = ("EraseRandom<", "LookUp<") if with_lookups else ("EraseRandom<",)
    for name in sorted({k for k in bench if k.startswith(families)}, key=_size_key):
        base, size = name.split("/") if "/" in name else (name, None)
        family = base.split("<")[0]
        if size is None:
            continue
        verb = "Copy, erase all of" if family == "EraseRandom" else "Lookup in"
        ops.append((family, "/" + size, f"{verb} {fmt_count_long(int(size))}"))
    return ops


def _size_key(name):
    family = name.split("<")[0]
    size = int(name.split("/")[1]) if "/" in name else 0
    return (family != "EraseRandom", size)


def set_panel_rows(bench, type_suffix, series):
    """Rows of the set chart for the element type 'type_suffix' ('RelocType', 'Int'...)."""
    rows = []
    # uint32_t lookups have their own chart, by number of elements
    amc_runs = {k: v for k, v in bench.items() if f"{SET_PREFIX[AMC]}{type_suffix}>" in k}
    for family, size, label in set_runs(amc_runs, with_lookups=type_suffix != "Int"):
        row = {}
        for s, _ in series:
            run = f"{family}<{SET_PREFIX[s]}{type_suffix}>{size}"
            if run in bench:
                row[s] = bench[run]
        if STD_ORDERED in row and AMC in row:
            rows.append((label, row))
    return rows


def vector_rows(bench, type_suffix):
    rows = []
    for op, label in VECTOR_OPS:
        if op == "Growing" and type_suffix != "Int":
            # Dominated by the allocations of the elements themselves (page faults), not by the growth of the vector
            continue
        row = {s: bench.get(f"{op}<{prefix}{type_suffix}>") for s, prefix in ((STD_ORDERED, "REF"), (AMC, "AMC"))}
        if None not in row.values():
            rows.append((label, row))
    return rows


def lookup_lines(bench, family):
    lines = {}
    for s, _ in SET_SERIES:
        pts = []
        for name, v in bench.items():
            m = re.fullmatch(rf"{family}<{SET_PREFIX[s]}Int>/(\d+)", name)
            if m:
                pts.append((int(m.group(1)), v))
        lines[s] = sorted(pts)
    return lines


def machine(context):
    l2 = next((c["size"] for c in context["caches"] if c["level"] == 2), None)
    l3 = next((c["size"] for c in context["caches"] if c["level"] == 3), None)
    caches = ", ".join(f"L{lvl} {size >> 20} MiB" for lvl, size in ((2, l2), (3, l3)) if size)
    return f"{context.get('cpu') or 'unknown CPU'} ({caches})"


def markdown_table(header, rows):
    widths = [max(len(r[i]) for r in [header] + rows) for i in range(len(header))]
    out = ["| " + " | ".join(h.ljust(w) for h, w in zip(header, widths)) + " |"]
    out.append("| " + " | ".join("-" * w if i == 0 else "-" * (w - 1) + ":" for i, w in enumerate(widths)) + " |")
    for r in rows:
        cells = (c.ljust(w) if i == 0 else c.rjust(w) for i, (c, w) in enumerate(zip(r, widths)))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--import", dest="raw_dir", help="directory of the Google Benchmark JSON outputs to import")
    parser.add_argument("--main", default="gcc13", help="compiler tag of the vector and set charts (default: gcc13)")
    args = parser.parse_args()

    if args.raw_dir:
        import_results(args.raw_dir)
    results, context = load_results()
    if args.main not in results:
        sys.exit(f"no results for compiler '{args.main}', available: {', '.join(sorted(results))}")
    main_name, where = compiler_name(args.main), machine(context)
    tags = sorted(results, key=lambda t: (t != args.main, t))
    tables = []

    # Vectors
    bench = results[args.main]["vectors"]
    panels = [(name, vector_rows(bench, suffix)) for suffix, name in VECTOR_TYPES]
    dumbbell_chart(
        os.path.join(DOCS, "bench_vectors.svg"), "amc::vector vs std::vector",
        f"Time per benchmark iteration, log scale - lower is better · {main_name} · {where}", VECTOR_SERIES, panels,
        "amc vs std::vector", "Benchmark times of std::vector and amc::vector for several operations and types.")
    for tag in tags:
        bench = results[tag]["vectors"]
        rows = []
        for suffix, type_name in VECTOR_TYPES:
            for label, row in vector_rows(bench, suffix):
                number, word = fmt_ratio(row[STD_ORDERED], row[AMC])
                rows.append([f"{type_name}: {label}", fmt_time(row[STD_ORDERED]), fmt_time(row[AMC]),
                             f"{number} {word}" if number else word])
        columns = ["Operation", "std::vector", "amc::vector", "amc"]
        tables.append((f"Vectors, {compiler_name(tag)}", markdown_table(columns, rows)))

    # SmallVector
    bench = results[args.main]["vectors"]
    panels = [(name, small_vector_rows(bench, suffix)) for suffix, name in VECTOR_TYPES]
    dumbbell_chart(
        os.path.join(DOCS, "bench_smallvector.svg"), f"amc::SmallVector<T, {SMALL_SIZE}> vs std::vector",
        [f"A vector is filled by emplace_back, read and destroyed. Small vectors have 1 to {SMALL_SIZE} elements, "
         f"large ones {SMALL_SIZE + 1} to {4 * SMALL_SIZE}.",
         f"Time per vector, log scale - lower is better · {main_name} · {where}"], SMALL_VECTOR_SERIES, panels,
        "SmallVector vs std::vector",
        "Time to fill, read and destroy std::vector, amc::vector and amc::SmallVector, from all small to all large.")
    for tag in tags:
        bench = results[tag]["vectors"]
        rows = []
        for suffix, type_name in VECTOR_TYPES:
            for label, row in small_vector_rows(bench, suffix):
                number, word = fmt_ratio(row[STD_ORDERED], row[AMC])
                rows.append([f"{type_name}: {label}"] + [fmt_time(row[s]) for s, _ in SMALL_VECTOR_SERIES] +
                            [f"{number} {word}" if number else word])
        columns = ["Vectors"] + [name for _, name in SMALL_VECTOR_SERIES] + ["SmallVector vs std::vector"]
        tables.append((f"SmallVector, {compiler_name(tag)}", markdown_table(columns, rows)))

    # Sets
    bench = results[args.main]["sets"]
    panels = [(name, set_panel_rows(bench, suffix, SET_SERIES)) for suffix, name in VECTOR_TYPES]
    dumbbell_chart(
        os.path.join(DOCS, "bench_sets.svg"), "amc::FlatSet vs std::set and std::unordered_set",
        f"Time per benchmark iteration, log scale - lower is better · {main_name} · {where}", SET_SERIES, panels,
        "amc vs std::set", "Benchmark times of std::set, std::unordered_set and amc::FlatSet for several operations.")
    for tag in tags:
        bench = results[tag]["sets"]
        rows = []
        for suffix, type_name in VECTOR_TYPES:
            for label, row in set_panel_rows(bench, suffix, SET_SERIES):
                number, word = fmt_ratio(row[STD_ORDERED], row[AMC])
                rows.append([f"{type_name}: {label}", fmt_time(row[STD_ORDERED]),
                             fmt_time(row[STD_HASHED]) if STD_HASHED in row else "",
                             fmt_time(row[AMC]), f"{number} {word}" if number else word])
        columns = ["Operation", "std::set", "std::unordered_set", "amc::FlatSet", "amc vs std::set"]
        tables.append((f"Sets, {compiler_name(tag)}", markdown_table(columns, rows)))

    # Lookups by size
    panels = [[(f"{compiler_name(tag)} · {mode}", lookup_lines(results[tag]["sets"], family)) for tag in tags]
              for family, mode in (("LookUp", "independent lookups"), ("LookUpChained", "chained lookups"))]
    lines_chart(
        os.path.join(DOCS, "bench_set_lookups.svg"), "uint32_t set lookups by number of elements",
        f"Time per lookup, log-log scale - lower is better · {where}", SET_SERIES, panels,
        "Lookup time of std::set, std::unordered_set and amc::FlatSet of uint32_t from 100 to 10 million elements.")
    for tag in tags:
        bench = results[tag]["sets"]
        rows = []
        for n in sorted({int(k.split("/")[1]) for k in bench if k.startswith("LookUp<")}):
            row = [fmt_count_long(n)]
            for s, _ in SET_SERIES:
                ind, chained = (bench[f"{f}<{SET_PREFIX[s]}Int>/{n}"] for f in ("LookUp", "LookUpChained"))
                row.append(f"{fmt_time(ind)} / {fmt_time(chained)}")
            rows.append(row)
        tables.append((f"uint32_t lookups (independent / chained), {compiler_name(tag)}",
                       markdown_table(["Elements"] + [name for _, name in SET_SERIES], rows)))

    # README tables
    with open(README) as f:
        readme = f.read()
    begin, end = readme.find(TABLES_BEGIN), readme.find(TABLES_END)
    if begin < 0 or end < 0:
        sys.exit(f"README.md misses the markers {TABLES_BEGIN} and {TABLES_END}")
    blocks = [f"<details><summary>{escape(title)}</summary>\n\n{table}\n\n</details>" for title, table in tables]
    generated = f"{TABLES_BEGIN}\n\n" + "\n\n".join(blocks) + f"\n\n{TABLES_END}"
    with open(README, "w") as f:
        f.write(readme[:begin] + generated + readme[end + len(TABLES_END):])
    print(f"updated {README}")


