def compiler_name(tag):
    """'gcc13' -> 'GCC 13', 'clang23' -> 'Clang 23'."""
    m = re.fullmatch(r"([a-z]+)(\d*)", tag)
    if not m:
        return tag
    name = {"gcc": "GCC", "clang": "Clang", "msvc": "MSVC", "appleclang": "Apple Clang"}.get(m.group(1), m.group(1))
    return f"{name} {m.group(2)}".strip()


def cpu_model():
    try:
        with open("/proc/cpuinfo") as f:
            for line in f:
                if line.startswith("model name"):
                    # 'AMD Ryzen AI 9 HX PRO 370 w/ Radeon 890M' -> 'AMD Ryzen AI 9 HX PRO 370'
                    return re.sub(r" w/ .*", "", line.split(":", 1)[1].strip())
    except OSError:
        pass
    return None


def import_results(raw_dir):
    """Stores the medians of the Google Benchmark JSON outputs of 'raw_dir' in docs/benchmarks/."""
    os.makedirs(RESULTS, exist_ok=True)
    paths = sorted(glob.glob(os.path.join(raw_dir, "*-*.json")))
    if not paths:
        sys.exit(f"no <benchmark>-<compiler>.json file in {raw_dir}")
    for path in paths:
        with open(path) as f:
            raw = json.load(f)
        context = {k: raw["context"][k] for k in ("date", "num_cpus", "mhz_per_cpu", "caches", "library_version")}
        context["cpu"] = cpu_model()
        medians = {}
        for b in raw["benchmarks"]:
            if b.get("run_type") == "aggregate" and b.get("aggregate_name") != "median":
                continue
            # 'Erase<T>/iterations:10000' -> 'Erase<T>'
            name = re.sub(r"/(iterations|repeats|min_time):[^/]*", "", b["run_name"])
            medians[name] = b["real_time"] * TIME_UNITS_NS[b["time_unit"]]
        out = os.path.join(RESULTS, os.path.basename(path))
        with open(out, "w") as f:
            json.dump({"context": context, "median_real_time_ns": medians}, f, indent=1, sort_keys=True)
            f.write("\n")
        print(f"imported {out}")


def load_results():
    """Returns {compiler tag: {benchmark kind: {run name: median time in ns}}} and the context of the first file."""
    results, context = {}, None
    for path in sorted(glob.glob(os.path.join(RESULTS, "*-*.json"))):
        kind, tag = os.path.splitext(os.path.basename(path))[0].split("-", 1)
        with open(path) as f:
            data = json.load(f)
        results.setdefault(tag, {})[kind] = data["median_real_time_ns"]
        context = context or data["context"]
    if not results:
        sys.exit(f"no results in {RESULTS}, run with --import first")
    return results, context


