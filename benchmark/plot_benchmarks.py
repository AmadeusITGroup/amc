class Svg:
    def __init__(self, width):
        self.width = width
        self.items = []

    def add(self, item):
        self.items.append(item)

    def text(self, x, y, s, cls, anchor="start", extra=""):
        self.add(f'<text x="{x:.1f}" y="{y:.1f}" class="{cls}" text-anchor="{anchor}"{extra}>{escape(s)}</text>')

    def line(self, x1, y1, x2, y2, cls):
        self.add(f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" class="{cls}"/>')

    def dot(self, x, y, series):
        """Filled dot for amc, ring for the std containers: they stay visible on top of each other."""
        if series in (AMC, AMC_VECTOR):
            self.add(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="4.5" class="dot {series}"/>')
        else:
            self.add(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="5.5" class="ring {series}"/>')

    def save(self, path, height, title, description):
        out = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.width}" height="{height:.0f}" '
            f'viewBox="0 0 {self.width} {height:.0f}" role="img" aria-labelledby="title desc">',
            f"<title id=\"title\">{escape(title)}</title>",
            f"<desc id=\"desc\">{escape(description)}</desc>",
            f"<style>{STYLE}</style>",
            f'<rect class="bg" width="{self.width}" height="{height:.0f}" rx="12"/>',
        ]
        with open(path, "w") as f:
            f.write("\n".join(out + self.items + ["</svg>", ""]))
        print(f"wrote {path}")


def snap_125(v, down):
    """Closest value of the 1, 2, 5, 10, 20... sequence below (or above) v."""
    e = 10.0 ** math.floor(math.log10(v))
    candidates = [k * e for k in (1, 2, 5, 10)]
    return max(c for c in candidates if c <= v * 1.000001) if down else min(c for c in candidates if c >= v / 1.000001)


class LogScale:
    """Maps [lo, hi], widened to the 1-2-5 sequence, to [x0, x1] (x1 < x0 for a vertical axis)."""

    def __init__(self, lo, hi, x0, x1):
        self.lo, self.hi = math.log10(snap_125(lo, True)), math.log10(snap_125(hi, False))
        self.x0, self.x1 = x0, x1

    def __call__(self, v):
        return self.x0 + (math.log10(v) - self.lo) / (self.hi - self.lo) * (self.x1 - self.x0)

    def decades(self):
        """Powers of 10 inside the domain, for the ticks."""
        return [10.0**e for e in range(math.ceil(self.lo - 1e-9), math.floor(self.hi + 1e-9) + 1)]


def legend(svg, x, y, entries, line_key=False):
    """Legend row: a colored key beside each name (text keeps the ink color)."""
    for series, name in entries:
        if line_key:
            svg.add(f'<line x1="{x:.1f}" y1="{y - 4:.1f}" x2="{x + 22:.1f}" y2="{y - 4:.1f}" class="line {series}"/>')
            svg.dot(x + 11, y - 4, series)
            x += 30
        else:
            svg.dot(x + 6, y - 4, series)
            x += 18
        svg.text(x, y, name, "label")
        x += 8.2 * len(name) + 24


def header(svg, left, title, subtitle):
    """Title and subtitle lines, returns the y of the legend row."""
    svg.text(left, 44, title, "title")
    y = 66
    for line in [subtitle] if isinstance(subtitle, str) else subtitle:
        svg.text(left, y, line, "subtitle")
        y += 18
    return y + 12


def dumbbell_chart(path, title, subtitle, series, panels, ratio_title, description):
    """One row per operation: a dot per container on a shared log time axis, and the speedup of the AMC series over the
    STD_ORDERED one.

    'series' is the ordered list of (series, container name), 'panels' a list of (panel title, rows), a row being
    (label, {series: time in ns}).
    """
    width, left, label_w, ratio_w, right = 880, 28, 230, 120, 28
    plot_x0, plot_x1 = left + label_w, width - right - ratio_w
    row_h, panel_head, axis_h, panel_gap = 30, 30, 26, 18
    values = [v for _, rows in panels for _, row in rows for v in row.values()]
    scale = LogScale(min(values), max(values), plot_x0 + 8, plot_x1 - 8)

    svg = Svg(width)
    legend_y = header(svg, left, title, subtitle)
    legend(svg, left, legend_y, series)
    svg.text(width - right, legend_y, ratio_title, "subtitle", anchor="end")

    y = legend_y + 22
    for panel_title, rows in panels:
        svg.text(left, y + 18, panel_title, "panel")
        top, bottom = y + panel_head, y + panel_head + row_h * len(rows)
        for d in scale.decades():
            svg.line(scale(d), top, scale(d), bottom, "grid")
            svg.text(scale(d), bottom + 17, fmt_tick_time(d), "tick", anchor="middle")
        svg.line(plot_x0, bottom, plot_x1, bottom, "axis")
        for i, (label, row) in enumerate(rows):
            cy = top + row_h * i + row_h / 2
            svg.text(left, cy + 4.5, label, "label")
            xs = [scale(v) for v in row.values()]
            svg.add(f'<line x1="{min(xs):.1f}" y1="{cy:.1f}" x2="{max(xs):.1f}" y2="{cy:.1f}" class="link"/>')
            for s, _ in series:  # amc is last: on top
                if s in row:
                    svg.dot(scale(row[s]), cy, s)
            number, word = fmt_ratio(row[STD_ORDERED], row[AMC])
            tspans = f'<tspan class="word">{word}</tspan>'
            if number:
                tspans = f'<tspan font-weight="600">{number}</tspan> ' + tspans
            svg.add(f'<text x="{width - right}" y="{cy + 4.5:.1f}" class="ratio" text-anchor="end">{tspans}</text>')
        y = bottom + axis_h + panel_gap
    svg.save(path, y, title, description)


def lines_chart(path, title, subtitle, series, panels, description):
    """Small multiples of lines on log-log axes shared by all panels.

    'panels' is a list of rows of (panel title, {series: [(x, time in ns)]}).
    """
    width, left, right, col_gap = 880, 28, 28, 36
    n_cols = max(len(r) for r in panels)
    panel_w = (width - left - right - col_gap * (n_cols - 1)) / n_cols
    panel_head, plot_h, axis_h, row_gap, y_label_w = 28, 190, 34, 18, 46
    xs = [x for row in panels for _, lines in row for pts in lines.values() for x, _ in pts]
    ys = [v for row in panels for _, lines in row for pts in lines.values() for _, v in pts]

    svg = Svg(width)
    legend_y = header(svg, left, title, subtitle)
    legend(svg, left, legend_y, series, line_key=True)

    y = legend_y + 22
    for row in panels:
        for col, (panel_title, lines) in enumerate(row):
            x0 = left + col * (panel_w + col_gap)
            sx = LogScale(min(xs), max(xs), x0 + y_label_w + 10, x0 + panel_w - 10)
            bottom = y + panel_head + plot_h
            sy = LogScale(min(ys), max(ys), bottom - 6, bottom - plot_h)

            svg.text(x0, y + 16, panel_title, "panel")
            for d in sy.decades():
                svg.line(x0 + y_label_w, sy(d), x0 + panel_w, sy(d), "grid")
                svg.text(x0 + y_label_w - 6, sy(d) + 4, fmt_tick_time(d), "tick", anchor="end")
            for xv in sorted({x for pts in lines.values() for x, _ in pts}):
                svg.text(sx(xv), bottom + 18, fmt_count(xv), "tick", anchor="middle")
            svg.line(x0 + y_label_w, bottom, x0 + panel_w, bottom, "axis")
            for s, _ in series:
                pts = lines.get(s)
                if not pts:
                    continue
                d_attr = " ".join(f"{'M' if i == 0 else 'L'}{sx(x):.1f},{sy(v):.1f}" for i, (x, v) in enumerate(pts))
                svg.add(f'<path d="{d_attr}" class="line {s}"/>')
                for x, v in pts:
                    svg.dot(sx(x), sy(v), s)
        y += panel_head + plot_h + axis_h + row_gap
    svg.text(left, y + 2, "Number of elements in the set, log scale", "subtitle")
    svg.save(path, y + 24, title, description)


