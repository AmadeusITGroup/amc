# Formatting


def fmt_time(ns):
    """Time with 3 significant digits at most, in the most readable unit."""
    for unit, scale in (("s", 1e9), ("ms", 1e6), ("µs", 1e3)):
        if ns >= scale:
            return f"{fmt_num(ns / scale)} {unit}"
    return f"{fmt_num(ns)} ns"


def fmt_num(x):
    if x >= 100:
        return f"{x:.0f}"
    if x >= 10:
        return f"{x:.1f}".rstrip("0").rstrip(".")
    return f"{x:.2f}".rstrip("0").rstrip(".")


def fmt_tick_time(ns):
    for unit, scale in (("s", 1e9), ("ms", 1e6), ("µs", 1e3)):
        if ns >= scale:
            return f"{ns / scale:g} {unit}"
    return f"{ns:g} ns"


def fmt_count(n):
    for suffix, scale in (("M", 1e6), ("k", 1e3)):
        if n >= scale and n % scale == 0:
            return f"{n / scale:g}{suffix}"
    return f"{n:g}"


def fmt_count_long(n):
    return f"{n:,}".replace(",", " ")


def fmt_ratio(ref, amc):
    """'2.3× faster', '1.5× slower' or 'same' (within 5 %)."""
    ratio = ref / amc
    if abs(math.log(ratio)) < math.log(1.05):
        return None, "same"
    word = "faster" if ratio > 1 else "slower"
    ratio = max(ratio, 1 / ratio)
    return (f"{ratio:.1f}" if ratio < 10 else f"{ratio:.0f}") + "×", word


